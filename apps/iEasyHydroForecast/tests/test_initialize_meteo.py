# ---------------------------------------------------------------------------
# End-to-end: run the embedded Python helper directly in dry-run, against a
# tmp_path containing copies of the fixture CSVs. This exercises the
# generator + filter logic without the Docker layer.
# ---------------------------------------------------------------------------


def _extract_embedded_helper() -> str:
    """Extract the inlined Python helper from the wrapper's heredoc.

    The wrapper writes the helper via `cat > $PYTHON_HELPER <<'PYEOF' ... PYEOF`.
    There is exactly one such heredoc; we slice it out and return its contents.
    """
    text = _WRAPPER.read_text(encoding="utf-8")
    start = text.find("cat > \"$PYTHON_HELPER\" <<'PYEOF'\n")
    assert start != -1, "wrapper no longer contains the PYEOF heredoc"
    # Advance past the opening line.
    nl = text.find("\n", start)
    body_start = nl + 1
    body_end = text.find("\nPYEOF\n", body_start)
    assert body_end != -1, "wrapper PYEOF terminator not found"
    return text[body_start:body_end]


def test_embedded_helper_dry_run_inventory(tmp_path: Path) -> None:
    """End-to-end: run the embedded helper in dry-run; inventory mentions both HRUs."""
    # Copy fixtures into a tmp dir that mimics
    # <data_ref_dir>/intermediate_data/hindcast_forcing.
    meteo_dir = tmp_path / "hindcast_forcing"
    meteo_dir.mkdir(parents=True)
    for src in _METEO_FIXTURES.glob("*.csv"):
        (meteo_dir / src.name).write_text(src.read_text(encoding="utf-8"))

    # Materialise the helper.
    helper_text = _extract_embedded_helper()
    helper_path = tmp_path / "meteo_helper.py"
    helper_path.write_text(helper_text)

    env = os.environ.copy()
    env["METEO_DATA_DIR"] = str(meteo_dir)
    env["STATION_FILTER"] = ""
    env["METEO_TYPE_FILTER"] = "both"
    env["BATCH_SIZE"] = "500"
    env["API_URL"] = "http://127.0.0.1:1/meteo/"  # unreachable; dry-run never hits it
    env["CUTOFF_T"] = ""
    env["CUTOFF_P"] = ""

    result = subprocess.run(
        [sys.executable, str(helper_path), "--dry-run"],
        capture_output=True,
        text=True,
        check=False,
        env=env,
    )
    assert result.returncode == 0, (
        f"helper dry-run failed: stdout={result.stdout!r}, stderr={result.stderr!r}"
    )
    out = result.stdout
    # Both HRU codes appear in the inventory listing.
    assert "hru=00001" in out, f"00001 missing from inventory: {out}"
    assert "hru=00002" in out, f"00002 missing from inventory: {out}"
    # Both meteo types appear.
    assert "meteo_type=T" in out and "meteo_type=P" in out
    # Distinct HRU count summary line.
    assert "distinct HRUs discovered (redacted count): 2" in out
    # Dashboard merge detected on the 00001 T pair.
    assert "dashboard=yes" in out
    # DRY_RUN guarantees no POST.
    assert "would POST" in out


