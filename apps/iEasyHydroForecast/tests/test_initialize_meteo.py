# ---------------------------------------------------------------------------
# Embedded-helper discovery logic (unit-level).
#
# We test the discovery logic by re-implementing the regex + glob walk that
# the wrapper's embedded Python helper performs. This is a CONTRACT test:
# if the wrapper changes the filename pattern, this test must change in
# lockstep. Keep the regex literal identical to the one in the wrapper's
# heredoc (`REANALYSIS_RE`).
# ---------------------------------------------------------------------------


_REANALYSIS_RE = re.compile(r"^(?P<hru>[A-Za-z0-9]+)_(?P<mt>[TP])_reanalysis\.csv$")


def _discover(
    root: Path,
    station_filter: str = "",
    meteo_type_filter: str = "both",
) -> list[tuple[str, str, Path, Path | None]]:
    """Replica of the wrapper's discover_reanalysis_files() for unit testing."""
    out: list[tuple[str, str, Path, Path | None]] = []
    for path in sorted(root.glob("*_reanalysis.csv")):
        m = _REANALYSIS_RE.match(path.name)
        if m is None:
            continue
        hru = m.group("hru")
        mt = m.group("mt")
        if station_filter and hru != station_filter:
            continue
        if meteo_type_filter != "both" and mt != meteo_type_filter:
            continue
        dash_name = path.name.replace(".csv", "_dashboard.csv")
        dash_path = path.with_name(dash_name)
        out.append((hru, mt, path, dash_path if dash_path.is_file() else None))
    return out


def test_hru_discovery_unit() -> None:
    """Glob discovers both sentinel HRU codes 00001 and 00002 from fixtures."""
    found = _discover(_METEO_FIXTURES)
    # Expect: 00001 T, 00001 P, 00002 T, 00002 P  -> 4 files, 2 distinct HRUs.
    hrus = sorted({hru for hru, _mt, _r, _d in found})
    assert hrus == ["00001", "00002"], f"expected ['00001', '00002'], got {hrus}"

    types_seen = sorted({mt for _hru, mt, _r, _d in found})
    assert types_seen == ["P", "T"], f"expected ['P', 'T'], got {types_seen}"

    # Dashboard merge: 00001 T has a dashboard sibling; 00001 P / 00002 T / 00002 P
    # do not. Verify the dashboard-detection branch.
    dash_lookup = {(hru, mt): d for hru, mt, _r, d in found}
    assert dash_lookup[("00001", "T")] is not None, (
        "expected 00001 T dashboard sidecar to be detected"
    )
    assert dash_lookup[("00001", "P")] is None
    assert dash_lookup[("00002", "T")] is None
    assert dash_lookup[("00002", "P")] is None


def test_hru_discovery_station_filter() -> None:
    """--station-filter 00001 restricts discovery to HRU 00001 only."""
    found = _discover(_METEO_FIXTURES, station_filter="00001")
    hrus = sorted({hru for hru, _mt, _r, _d in found})
    assert hrus == ["00001"], f"station-filter leaked: {hrus}"
    # Both T and P for 00001 are still returned.
    types = sorted({mt for _hru, mt, _r, _d in found})
    assert types == ["P", "T"]


def test_meteo_type_filter_T_only() -> None:
    """--meteo-type T discovers only T-reanalysis CSVs."""
    found = _discover(_METEO_FIXTURES, meteo_type_filter="T")
    # 00001_T + 00002_T -> two files; no P.
    types = {mt for _hru, mt, _r, _d in found}
    assert types == {"T"}, f"meteo-type T leaked: {types}"
    hrus = sorted({hru for hru, _mt, _r, _d in found})
    assert hrus == ["00001", "00002"]


def test_meteo_type_filter_P_only() -> None:
    """--meteo-type P discovers only P-reanalysis CSVs."""
    found = _discover(_METEO_FIXTURES, meteo_type_filter="P")
    types = {mt for _hru, mt, _r, _d in found}
    assert types == {"P"}, f"meteo-type P leaked: {types}"


def test_meteo_type_and_station_filter_combined() -> None:
    """--station-filter 00001 + --meteo-type P leaves one file."""
    found = _discover(_METEO_FIXTURES, station_filter="00001", meteo_type_filter="P")
    assert len(found) == 1, f"expected exactly 1 match, got {len(found)}"
    hru, mt, _rpath, _dpath = found[0]
    assert hru == "00001"
    assert mt == "P"


