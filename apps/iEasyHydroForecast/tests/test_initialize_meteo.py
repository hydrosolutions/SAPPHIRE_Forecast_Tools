"""Tests for bin/initialize_meteo_history.sh (Phase P1b).

These tests exercise:
- the wrapper's --help and missing-env-file argument paths (subprocess-level);
- the embedded Python helper's HRU discovery + filter logic (unit-level,
  by importing the helper module from a synthetic file tree).

The helper module is generated by the wrapper at runtime as a Python script
written into the deployment log dir, then mounted into Docker. To test the
discovery + filter logic deterministically without Docker, we import the
helper-equivalent functions inline here (re-using the same regex contract
that the wrapper writes — see REANALYSIS_RE below). The integration of
those functions is exercised by running the embedded script via the
subprocess test path below using stdin redirection of the heredoc.
"""

